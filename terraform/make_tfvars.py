"""
Creates terraform/terraform.tfvars for you - no copying of keys by hand.

Usage (from the terraform folder, venv active or any Python 3):
    python make_tfvars.py

It reads GEMINI_API_KEY and GITHUB_TOKEN from backend/.env, finds your public
IP (for SSH access), takes the repo URL from git, checks your SSH key exists,
and asks you to choose the website password (hidden while you type).
terraform.tfvars is git-ignored, so the secrets never reach GitHub.
"""

import getpass
import ipaddress
import os
import subprocess
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ENV_PATH = os.path.join(HERE, "..", "backend", ".env")
OUT_PATH = os.path.join(HERE, "terraform.tfvars")
SSH_KEY = os.path.join(os.path.expanduser("~"), ".ssh", "id_ed25519.pub")


def read_env() -> dict[str, str]:
    values = {}
    if os.path.exists(ENV_PATH):
        with open(ENV_PATH, encoding="utf-8-sig") as f:
            for line in f:
                line = line.strip()
                if line and not line.startswith("#") and "=" in line:
                    key, value = line.split("=", 1)
                    values[key.strip()] = value.strip().strip('"').strip("'")
    return values


def hcl(value: str) -> str:
    """Quote a value as an HCL string (escape quotes, backslashes and template markers)."""
    value = value.replace("\\", "\\\\").replace('"', '\\"').replace("${", "$${").replace("%{", "%%{")
    return f'"{value}"'


def public_ip() -> str:
    try:
        with urllib.request.urlopen("https://checkip.amazonaws.com", timeout=10) as resp:
            ip = resp.read().decode().strip()
    except OSError:
        ip = input("Could not detect your public IP. Open https://checkip.amazonaws.com and type it: ").strip()
    ipaddress.IPv4Address(ip)  # raises ValueError if it is not an IP
    return ip


def repo_url() -> str:
    try:
        url = subprocess.run(["git", "remote", "get-url", "origin"], cwd=HERE, capture_output=True,
                             text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        url = ""
    if not url.startswith("https://github.com/"):
        url = "https://github.com/advait3110/devops-ai-dashboard.git"
    return url


def ask_password() -> str:
    while True:
        pw = getpass.getpass("Choose the website password (min 8 characters, hidden): ")
        if len(pw) < 8:
            print("  Too short, try again.")
            continue
        if getpass.getpass("Type it again: ") != pw:
            print("  The two passwords differ, try again.")
            continue
        return pw


def main() -> None:
    if not os.path.exists(SSH_KEY):
        sys.exit(f"ERROR: SSH key {SSH_KEY} not found. Run:  ssh-keygen -t ed25519   (press Enter 3 times)")

    env = read_env()
    gemini = env.get("GEMINI_API_KEY", "")
    github = env.get("GITHUB_TOKEN", "")
    ip = public_ip()
    url = repo_url()
    print(f"Your IP (SSH allowed from): {ip}")
    print(f"Repository:                 {url}")
    print(f"Gemini key from .env:       {'found' if gemini else 'MISSING (AI assistant will be off)'}")
    print(f"GitHub token from .env:     {'found' if github else 'not set (pipelines limited to 60 API calls/hour)'}")
    password = ask_password()

    lines = [
        "# Generated by make_tfvars.py - git-ignored, contains secrets. Do not share.",
        'region                  = "ap-south-1"',
        'instance_type           = "t3.micro"',
        f"allowed_cidr            = {hcl(ip + '/32')}",
        'ssh_public_key_path     = "~/.ssh/id_ed25519.pub"',
        f"repo_url                = {hcl(url)}",
        'repo_branch             = "main"',
        f"gemini_api_key          = {hcl(gemini)}",
        f"github_token            = {hcl(github)}",
        'site_username           = "admin"',
        f"site_password           = {hcl(password)}",
        'domain_name             = ""',
        "enable_monitoring_stack = false",
        'alarm_email             = ""',
    ]
    with open(OUT_PATH, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"\nOK: wrote {OUT_PATH}")
    print("Website login will be:  admin / <the password you just chose>")


if __name__ == "__main__":
    main()
