/*
 * "Explain with AI" side panel used by CI/CD, Containers, Logs and Alerts.
 * It sends the failing output to POST /api/ai/analyze and shows Gemini's
 * Summary / Root cause / Fix / Prevention answer.
 */
import { Sparkles, X } from "lucide-react";
import { useEffect, useState } from "react";
import { api } from "../api";
import Markdown from "./Markdown";
import { Notice } from "./ui";

export function ExplainButton({ onClick, label = "Explain with AI", small = false }) {
  return (
    <button className={`btn ai ${small ? "sm" : ""}`} onClick={onClick}>
      <Sparkles size={small ? 14 : 16} />
      {label}
    </button>
  );
}

/** request = { title, text, source, context } | null */
export default function AiExplainPanel({ request, onClose }) {
  const [state, setState] = useState({ loading: false, result: null, error: null });

  useEffect(() => {
    if (!request) return undefined;
    let cancelled = false;
    // eslint-disable-next-line react-hooks/set-state-in-effect -- start of an async request
    setState({ loading: true, result: null, error: null });
    api
      .post("/api/ai/analyze", { text: request.text, source: request.source, context: request.context || "" })
      .then((r) => !cancelled && setState({ loading: false, result: r, error: null }))
      .catch((e) => !cancelled && setState({ loading: false, result: null, error: e }));
    return () => {
      cancelled = true;
    };
  }, [request]);

  useEffect(() => {
    const onKey = (e) => e.key === "Escape" && onClose();
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [onClose]);

  if (!request) return null;
  return (
    <div className="drawer-backdrop" onClick={onClose}>
      <aside
        className="drawer"
        role="dialog"
        aria-modal="true"
        aria-label="AI analysis"
        onClick={(e) => e.stopPropagation()}
      >
        <div className="drawer-head">
          <div>
            <h2>
              <Sparkles size={18} /> AI analysis
            </h2>
            <p className="panel-sub">{request.title}</p>
          </div>
          <button className="btn ghost icon" onClick={onClose} aria-label="Close">
            <X size={18} />
          </button>
        </div>
        <div className="drawer-body">
          {state.loading && (
            <div className="thinking">
              <span className="pulse-dot" /> Gemini is reading {request.source}…
            </div>
          )}
          <Notice error={state.error} />
          {state.result && (
            <>
              <Markdown>{state.result.analysis}</Markdown>
              <p className="model-note">
                Generated by {state.result.model}. Secrets were masked before sending. Check commands before running them.
              </p>
            </>
          )}
        </div>
      </aside>
    </div>
  );
}
